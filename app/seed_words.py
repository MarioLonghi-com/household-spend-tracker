def load_catalog() -> dict[str, dict[str, str]]:
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


_catalog: dict[str, dict[str, str]] | None = None


def catalog() -> dict[str, dict[str, str]]:
    global _catalog
    if _catalog is None:
        _catalog = load_catalog()
    return _catalog


def resolve(locale: str | None) -> str | None:
    """The catalog locale to seed from, or None for English.

    Exact first, then the language alone (``pt-PT`` takes ``pt-BR``), the same
    rule the client negotiates by. Only a locale holding reviewed words counts.
    """
    if not locale or not LOCALE_TAG.fullmatch(locale):
        return None
    held = {one: words for one, words in catalog().items() if words}
    for one in held:
        if one.lower() == locale.lower():
            return one
    language = locale.split("-")[0].lower()
    for one in held:
        if one.split("-")[0].lower() == language:
            return one
    return None


def word(message_id: str, locale: str | None = None) -> str:
    """One seeded word in ``locale``, or in English where it has none."""
    chosen = resolve(locale)
    if chosen is not None:
        translated = catalog()[chosen].get(message_id)
        if translated:
            return translated
    return ENGLISH[message_id]


def translations(message_id: str) -> list[str]:
    """Every reviewed translation of one word, in every locale, English left out."""
    return sorted(
        {words[message_id] for words in catalog().values() if words.get(message_id)}
        - {ENGLISH[message_id]}
    )
