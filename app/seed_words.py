"""The words a new household is seeded with, and their translations (#268).

A household starts with a category tree and, once an account is opened with a
balance, an "Opening balance" payee. Both are ordinary data from the moment
they are written: a person renames them like anything they typed, and nothing
stores which language they were seeded in.

Each word has a stable id here and the same id in the client's catalogs
(`client/src/lib/seedWords.ts`), so a translator meets it in the `.po` file
beside every other message. The server cannot read those catalogs at run time
-- the image carries the built client, not its sources -- so
`app/seed_catalog.json` holds what it needs from them: **reviewed
translations only**, generated by `scripts/seed_catalog.py`. A draft (`#,
fuzzy`) is never seeded, for the same reason the client never serves one, so
until #58 reviews a language every household is seeded in English whatever is
asked for.

`tests/test_seed_words.py` holds the three together: the ids and English here
equal the client's, and the JSON is what the script would write today.
"""

